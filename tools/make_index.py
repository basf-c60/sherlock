"""Regenerate tools/experiments/INDEX.md: which experiment scripts the written text cites."""
import glob, os, ast
win = {'replay_log.py': 'replay the first N commands from a fresh boot; saves /tmp/replay_log.snap (about 17 s for the whole win)',
       'replay_verbose.py': 'same, printing clock, room and reply per command and the final text',
       'minimize_cmds.py': 'drop commands that are not needed for the win',
       'route_coverage.py': 'which routine entry points a command file executes (one-shot breakpoints)',
       'probe_routines.py': 'check the stated postconditions of five small routines while a command file is typed'}
cited, scratch = [], []
for f in sorted(glob.glob('tools/experiments/*.py')):
    b = os.path.basename(f)
    if b in win: continue
    try: d = (ast.get_docstring(ast.parse(open(f).read())) or '').strip().split('\n')[0][:110]
    except Exception: d = ''
    n = sum(open(p).read().count(b) for p in glob.glob('source/overlay_*.py') + glob.glob('source/*.md') + ['game.skool'])
    (cited if n else scratch).append((b, n, d))
o = ["# Experiment scripts: which are evidence and which are scratch", "",
     "Generated by tools/make_index.py by counting how often each script's name appears in game.skool, the overlays and the notes. A script with citations is one the written claims lean on. A script with none is exploratory: it may be where an idea was first tried and its result may have been re-checked by hand or by a later script, but nothing in the text points at it, so don't treat its output as evidence.", "",
     "## Replaying and checking the route (what the README uses)", ""]
o += ["- `%s`: %s" % (k, v) for k, v in win.items()]
o += ["- `playthrough/`: v11_full_win.cmds (444 lines), v12_clean_win.cmds (372 lines, minimal), v13_shadow_lestrade.cmds (368 lines, a second winning route), each with a transcript; `endings/` holds every ending reached and the attempts that failed.", "",
      "## Cited by the disassembly text (evidence)", ""]
o += ["- `%s` (%d citations)%s" % (b, n, ': ' + d if d else '') for b, n, d in cited]
o += ["", "## Not cited anywhere (exploratory / scratch)", ""]
o += ["- `%s`%s" % (b, ': ' + d if d else '') for b, n, d in scratch]
open('tools/experiments/INDEX.md', 'w').write('\n'.join(o) + '\n')
print(len(cited), 'cited,', len(scratch), 'scratch')
